/**
 * Static prerender — runs after the client and server builds (see "build" in
 * package.json).
 *
 * For every app route it renders the real page with the app's own components
 * (dist-ssr/entry-server.js) into dist/<route>.html, with a search title and
 * description, canonical link, Open Graph / Twitter tags, a share image and
 * JSON-LD structured data. It also writes a Markdown twin of each lesson,
 * llms.txt and llms-full.txt for AI agents, sitemap.xml with per-page lastmod
 * from git history, robots.txt, 404.html and Netlify _redirects.
 *
 * Canonical and sitemap URLs need the production origin: set SITE_URL
 * (e.g. SITE_URL=https://example.org npm run build). Netlify's URL and
 * Vercel's VERCEL_PROJECT_PRODUCTION_URL are picked up automatically.
 * Optional: GOOGLE_SITE_VERIFICATION, BING_SITE_VERIFICATION (ownership meta
 * tags) and INDEXNOW_KEY (writes the IndexNow key file).
 * `--dist=<dir>` prerenders another build directory (used for local checks).
 */
import { execFileSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { loadContent, ROOT } from '../validation/load-content'
import { buildRedirects, buildSitemap, ogImageFile, outputFileFor, parseLabMeta, renderDocument, trailingSlashRedirect } from './html'
import { buildLlmsFullTxt, buildLlmsTxt, buildRobots, topicMarkdown, type MarkdownContext } from './markdown'
import { buildRoutes, buildSiteJsonLd, escapeHtml, SITE_NAME, topicMarkdownPath, type ContentDates, type PrerenderRoute } from './routes'

const distArg = process.argv.find((a) => a.startsWith('--dist='))?.slice('--dist='.length)
const DIST = distArg ? path.resolve(distArg) : path.join(ROOT, 'dist')
const SSR_ENTRY = path.join(ROOT, 'dist-ssr', 'entry-server.js')
const REGISTRY = path.join(ROOT, 'src/features/labs/registry.ts')
const PUBLIC = path.join(ROOT, 'public')
const PREVIEW_ORIGIN = 'http://localhost:4173'

function resolveSiteUrl(): { url: string; fromEnv: boolean } {
  const env = process.env
  const candidates = [env.SITE_URL, env.URL, env.VERCEL_PROJECT_PRODUCTION_URL && `https://${env.VERCEL_PROJECT_PRODUCTION_URL}`]
  for (const c of candidates) {
    if (!c) continue
    try {
      const u = new URL(c)
      if (u.protocol === 'http:' || u.protocol === 'https:') {
        return { url: `${u.origin}${u.pathname.replace(/\/+$/, '')}`, fromEnv: true }
      }
    } catch {
      /* try the next candidate */
    }
  }
  return { url: PREVIEW_ORIGIN, fromEnv: false }
}

function resolveBasePath(): string {
  const configured = process.env.PUBLIC_BASE_PATH?.trim() || '/'
  const leadingSlash = configured.startsWith('/') ? configured : `/${configured}`
  return leadingSlash === '/' ? '/' : `${leadingSlash.replace(/\/+$/, '')}/`
}

/** First and last commit dates of a file (ISO), or undefined without git history. */
function gitDates(relFile: string): ContentDates | undefined {
  try {
    const out = execFileSync('git', ['log', '--follow', '--format=%cI', '--', relFile], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] })
    const dates = out.split('\n').filter(Boolean)
    return dates.length ? { published: dates.at(-1), modified: dates[0] } : undefined
  } catch {
    return undefined
  }
}

/** Share images live in public/og/ (generated by `npm run og:images`); a route uses its own, else the default. */
function imageFor(routePath: string): string | undefined {
  const file = ogImageFile(routePath)
  return existsSync(path.join(PUBLIC, file)) ? `/${file}` : undefined
}

async function main() {
  const templatePath = path.join(DIST, 'index.html')
  if (!existsSync(templatePath)) throw new Error(`${templatePath} not found — run \`vite build\` first`)
  if (!existsSync(SSR_ENTRY)) throw new Error(`${SSR_ENTRY} not found — run \`vite build --ssr src/entry-server.tsx --outDir dist-ssr\` first`)
  const template = await readFile(templatePath, 'utf8')
  const { render } = (await import(pathToFileURL(SSR_ENTRY).href)) as { render: (path: string, basename: string) => Promise<{ html: string; status: number }> }

  const content = loadContent()
  if (content.errors.length) {
    content.errors.forEach((e) => console.error(`[prerender] ${e.file}: ${e.message}`))
    throw new Error(`${content.errors.length} content file(s) failed validation; run npm run validate:content`)
  }
  const labs = existsSync(REGISTRY) ? parseLabMeta(await readFile(REGISTRY, 'utf8')) : []
  if (!labs.length) console.warn('[prerender] warning: no labs parsed from src/features/labs/registry.ts; /labs/<id> pages skipped')

  const { url: siteUrl, fromEnv } = resolveSiteUrl()
  const basePath = resolveBasePath()
  if (!fromEnv) console.warn(`[prerender] warning: SITE_URL not set; canonical and sitemap URLs use ${PREVIEW_ORIGIN}`)

  // Content history: each lesson's own file; pages without one use the span of all lessons.
  const topicDates = new Map<string, ContentDates | undefined>()
  for (const [id, file] of content.topicFiles) topicDates.set(id, gitDates(file))
  const known = [...topicDates.values()].filter((d): d is ContentDates => !!d)
  const siteDates: ContentDates | undefined = known.length
    ? { published: known.map((d) => d.published!).sort()[0], modified: known.map((d) => d.modified!).sort().at(-1) }
    : undefined
  const dates = (key: string) => (key === 'site' ? siteDates : (topicDates.get(key) ?? siteDates))

  const routes = buildRoutes({ categories: content.categories, topics: content.topics, labs, pioneers: content.pioneers, siteUrl, dates, imageFor })
  const logo = existsSync(path.join(PUBLIC, 'icons', 'autoverse-512.png')) ? '/icons/autoverse-512.png' : '/icons/autoverse.svg'
  const siteJsonLd = buildSiteJsonLd(siteUrl, logo)
  const verification = { google: process.env.GOOGLE_SITE_VERIFICATION?.trim() || undefined, bing: process.env.BING_SITE_VERIFICATION?.trim() || undefined }

  const seen = new Set<string>()
  let rendered = 0
  for (const route of routes) {
    if (seen.has(route.path)) throw new Error(`duplicate route ${route.path}`)
    seen.add(route.path)
    const appHtml = route.ssr === false ? undefined : (await render(route.path, basePath)).html
    if (appHtml !== undefined) rendered++
    const file = path.join(DIST, outputFileFor(route.path))
    await mkdir(path.dirname(file), { recursive: true })
    await writeFile(file, renderDocument(template, route, { siteUrl, basePath, appHtml, siteJsonLd, verification }))
  }

  // 404.html doubles as the single-page fallback for paths without a file (and personal pages such as certificates).
  const notFound: PrerenderRoute = {
    path: '/404',
    title: `Page not found · ${SITE_NAME}`,
    description: 'This page does not exist. Browse AutoVerse lessons and laboratories instead.',
    ogType: 'website',
    bodyHtml: `<h1>Page not found</h1><p>${escapeHtml('There is no page at this address.')}</p><ul><li><a href="/">Home</a></li><li><a href="/learn">All topics</a></li><li><a href="/labs">Labs</a></li></ul>`,
    priority: 0,
    noindex: true,
  }
  await writeFile(path.join(DIST, '404.html'), renderDocument(template, notFound, { siteUrl, basePath, extraHead: trailingSlashRedirect(basePath) }))

  // AI agents: Markdown twins, llms.txt, llms-full.txt.
  const mdContext: MarkdownContext = { siteUrl, categories: content.categories, topics: content.topics, labs, pioneers: content.pioneers ?? [] }
  for (const topic of content.topics) {
    const file = path.join(DIST, topicMarkdownPath(topic).replace(/^\/+/, ''))
    await mkdir(path.dirname(file), { recursive: true })
    await writeFile(file, topicMarkdown(topic, mdContext))
  }
  await writeFile(path.join(DIST, 'llms.txt'), buildLlmsTxt(mdContext))
  await writeFile(path.join(DIST, 'llms-full.txt'), buildLlmsFullTxt(mdContext))

  const buildDate = new Date().toISOString().slice(0, 10)
  await writeFile(path.join(DIST, 'sitemap.xml'), buildSitemap(routes, siteUrl, buildDate))
  await writeFile(path.join(DIST, 'robots.txt'), buildRobots(siteUrl, ['/progress', '/certificate/']))

  const indexNowKey = process.env.INDEXNOW_KEY?.trim()
  if (indexNowKey) {
    if (!/^[a-zA-Z0-9-]{8,128}$/.test(indexNowKey)) throw new Error('INDEXNOW_KEY must be 8–128 letters, digits or dashes')
    await writeFile(path.join(DIST, `${indexNowKey}.txt`), indexNowKey)
  }

  const redirectsPath = path.join(DIST, '_redirects')
  const existing = existsSync(redirectsPath) ? await readFile(redirectsPath, 'utf8') : '/*  /index.html  200\n'
  await writeFile(redirectsPath, buildRedirects(routes, existing))

  const count = (prefix: string) => routes.filter((r) => r.path.startsWith(prefix)).length
  console.log(
    `[prerender] ${routes.length} pages (${rendered} rendered with content; ${count('/topics/')} topics, ${count('/learn/')} categories, ${count('/labs/')} labs) + ${content.topics.length} Markdown lessons, llms.txt, llms-full.txt, sitemap.xml, robots.txt, 404.html → ${path.relative(ROOT, DIST) || '.'}/ (origin ${siteUrl}${known.length ? '' : '; no git history: dates omitted'})`,
  )
}

main().catch((error: unknown) => {
  console.error('[prerender] failed:', error instanceof Error ? error.message : error)
  process.exitCode = 1
})
